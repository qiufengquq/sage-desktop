export function exercisesOf(kind: ExerciseKind): Exercise[] {
  return exerciseBank[kind] ?? [];
}

const flatten = Object.values(exerciseBank).flat();

export function exerciseById(id: string): Exercise | undefined {
  return flatten.find((e) => e.id === id);
}

export function exercisesByIds(ids: string[]): Exercise[] {
  return ids
    .map((id) => exerciseById(id))
    .filter((e): e is Exercise => Boolean(e));
}

/** 训练入口统一估算：题目数 × 单题时长 */
export function estimateMinutes(items: number) {
  return Math.max(2, Math.round((items * 55) / 60));
}
